(function () {
  var $ = function (s, r) { return (r || document).querySelector(s); };
  var $$ = function (s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); };

  // Footer year
  $('#year').textContent = new Date().getFullYear();

  // Mobile menu
  var nav = $('#nav'), burger = $('#burger');
  function setMenu(open) {
    nav.classList.toggle('open', open);
    burger.setAttribute('aria-expanded', String(open));
  }
  burger.addEventListener('click', function () { setMenu(!nav.classList.contains('open')); });
  $$('#menu a').forEach(function (a) { a.addEventListener('click', function () { setMenu(false); }); });
  document.addEventListener('keydown', function (e) { if (e.key === 'Escape') setMenu(false); });

  // Highlight current section in the menu
  var links = $$('#menu a');
  if ('IntersectionObserver' in window) {
    var spy = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (!en.isIntersecting) return;
        links.forEach(function (a) { a.classList.toggle('on', a.getAttribute('href') === '#' + en.target.id); });
      });
    }, { rootMargin: '-45% 0px -50% 0px' });
    $$('main section[id]').forEach(function (s) { spy.observe(s); });
  }

  // Project filters
  var filterBtns = $$('.filters button'), cards = $$('.card'), count = $('#count');
  filterBtns.forEach(function (btn) {
    btn.addEventListener('click', function () {
      var f = btn.getAttribute('data-f'), shown = 0;
      filterBtns.forEach(function (b) {
        var on = b === btn;
        b.classList.toggle('on', on);
        b.setAttribute('aria-pressed', String(on));
      });
      cards.forEach(function (c) {
        var match = f === 'all' || c.getAttribute('data-tags').split(' ').indexOf(f) > -1;
        c.hidden = !match;
        if (match) shown++;
      });
      count.textContent = shown;
    });
  });

  // Project details dialog
  var data = JSON.parse($('#data').textContent), dlg = $('#dlg'), lastFocus = null;
  function openProject(id) {
    var p = data[id];
    if (!p) return;
    $('#d-kind').textContent = p.kind;
    $('#d-name').textContent = p.name;
    $('#d-desc').textContent = p.desc;
    $('#d-stack').innerHTML = '';
    p.stack.forEach(function (t) {
      var li = document.createElement('li');
      li.textContent = t;
      $('#d-stack').appendChild(li);
    });
    var box = $('#d-links');
    box.innerHTML = '';
    p.links.forEach(function (l) {
      var a = document.createElement('a');
      a.href = l[1]; a.target = '_blank'; a.rel = 'noopener';
      a.textContent = l[0] + ' ↗';
      box.appendChild(a);
    });
    if (typeof dlg.showModal === 'function') dlg.showModal(); else dlg.setAttribute('open', '');
  }
  $$('.card button').forEach(function (b) {
    b.addEventListener('click', function () { lastFocus = b; openProject(b.getAttribute('data-id')); });
  });
  dlg.addEventListener('click', function (e) { if (e.target === dlg) dlg.close(); });
  dlg.addEventListener('close', function () { if (lastFocus) lastFocus.focus(); });

  // Optional hero photo: add a transparent photo.png next to index.html and it replaces the code card.
  var probe = new Image();
  probe.onload = function () {
    var fig = $('#photo');
    probe.alt = 'Adarsh Patil';
    fig.appendChild(probe);
    fig.hidden = false;
    $('#code').hidden = true;
  };
  probe.src = 'photo.png';
})();

// Mouse "website creation" animation: labelled cursors click the hero into place,
// then stay on as followers of the real mouse.
(function () {
  var html = document.documentElement;
  var reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var box = document.getElementById('agents');
  var skipBtn = document.getElementById('skipbuild');
  var replay = document.getElementById('replay');
  if (replay) replay.addEventListener('click', function () {
    try { sessionStorage.removeItem('built'); } catch (e) {}
    window.scrollTo(0, 0);
    location.hash = '';
    location.reload();
  });
  if (reduce || !box) return;

  // Mark everything below the hero as "generated by cursors while you scroll".
  var SB = ['.sec-head', '.filters', '.card', '.marquee', '.results h2', '.badge', '.res-left p', '.res-list li',
    '.about-l h2', '.about-l p', '.about-r h3', '.skills > div', '.what h2', '.lead', '.steps li', '.quote',
    '.contact h2', '.ct-l p', '.start', '.ct-list li', '.ct-box', '.foot'];
  var sbEls = [];
  SB.forEach(function (sel) {
    Array.prototype.forEach.call(document.querySelectorAll(sel), function (el) {
      if (sbEls.indexOf(el) < 0) { el.classList.add('sb'); sbEls.push(el); }
    });
  });

  var specs = [['Layout', '#FF3B3B'], ['Type', '#FFFFFF'], ['Color', '#FF9A9A'], ['Code', '#5CC8FF']];
  var arrow = '<svg viewBox="0 0 24 24"><path d="M3 2l17 8.2-7.2 2.1L10 20z"/></svg>';
  var agents = specs.map(function (s, i) {
    var a = document.createElement('div');
    a.className = 'agent';
    a.style.setProperty('--c', s[1]);
    a.innerHTML = arrow + '<span>' + s[0] + '</span>';
    var x = i % 2 ? window.innerWidth + 40 : -40, y = i < 2 ? -40 : window.innerHeight + 40;
    a.style.transform = 'translate(' + x + 'px,' + y + 'px)';
    a.__x = x; a.__y = y;
    box.appendChild(a);
    return a;
  });

  function place(a, x, y) { a.__x = x; a.__y = y; a.style.transform = 'translate(' + x + 'px,' + y + 'px)'; }
  function ping(a, x, y) {
    var p = document.createElement('i');
    p.className = 'ping';
    p.style.setProperty('--c', a.style.getPropertyValue('--c'));
    p.style.left = x + 'px'; p.style.top = y + 'px';
    box.appendChild(p);
    setTimeout(function () { p.remove(); }, 650);
  }

  var mx = window.innerWidth * 0.6, my = window.innerHeight * 0.5, moved = false, ambient = false;
  window.addEventListener('mousemove', function (e) { mx = e.clientX; my = e.clientY; moved = true; }, { passive: true });

  // Scroll build: cursors fly to each element as it enters the screen and click it into place.
  var sbStarted = false, noAgents = false, queue = [], pumping = false;
  function kindOf(el) {
    if (el.matches('.card, .res-list li, .skills > div, .steps li, .ct-list li, .sec-head')) return 0;
    if (el.matches('.quote, .ct-box, .badge, .marquee')) return 2;
    if (el.matches('.filters, .start, .foot')) return 3;
    return 1;
  }
  function reveal(el) { el.classList.add('sbd'); }
  function work(el) {
    var r = el.getBoundingClientRect();
    if (noAgents || r.bottom < 0 || r.top > window.innerHeight) { reveal(el); return; }
    var k = kindOf(el), a = agents[k];
    if (a.__busy) a = agents.filter(function (x) { return !x.__busy; })[0];
    if (!a) { reveal(el); return; }
    a.__busy = true;
    a.classList.remove('idle');
    var x = Math.min(Math.max(r.left + Math.min(r.width * 0.6, 420), 12), window.innerWidth - 40);
    var y = Math.min(Math.max(r.top + Math.min(r.height * 0.5, 160), 12), window.innerHeight - 40);
    place(a, x, y);
    setTimeout(function () { ping(a, x + 2, y + 2); reveal(el); }, 420);
    setTimeout(function () { a.classList.add('idle'); a.__busy = false; }, 950);
  }
  function pump() {
    if (pumping) return;
    pumping = true;
    (function next() {
      var el = queue.shift();
      if (!el) { pumping = false; return; }
      work(el);
      setTimeout(next, 170);
    })();
  }
  function startScrollBuild() {
    if (sbStarted) return;
    sbStarted = true;
    if (!('IntersectionObserver' in window)) { sbEls.forEach(reveal); return; }
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (!en.isIntersecting || en.target.__q) return;
        en.target.__q = true;
        io.unobserve(en.target);
        queue.push(en.target);
        if (queue.length > 8) reveal(queue.shift());
        pump();
      });
    }, { threshold: 0.15, rootMargin: '0px 0px -6% 0px' });
    sbEls.forEach(function (el) { io.observe(el); });
    // Anything already scrolled past (page reload mid-way, anchor jumps) appears at once.
    var ticking = false;
    function sweep() {
      ticking = false;
      sbEls.forEach(function (el) {
        if (!el.classList.contains('sbd') && el.getBoundingClientRect().bottom < 0) { el.__q = true; reveal(el); }
      });
    }
    window.addEventListener('scroll', function () { if (!ticking) { ticking = true; requestAnimationFrame(sweep); } }, { passive: true });
    sweep();
  }

  function startAmbient() {
    if (ambient) return;
    ambient = true;
    startScrollBuild();
    if (window.matchMedia('(pointer: coarse)').matches) {
      noAgents = true;
      agents.forEach(function (a) { a.classList.add('gone'); });
      return;
    }
    agents.forEach(function (a) { a.classList.add('idle'); });
    function loop(t) {
      agents.forEach(function (a, i) {
        if (a.__busy) return;
        var r = 46 + i * 22, w = t * 0.0012 + i * 1.7;
        var tx = (moved ? mx : window.innerWidth * 0.62) + Math.cos(w) * r;
        var ty = (moved ? my : window.innerHeight * 0.5) + Math.sin(w * 1.15) * r * 0.8;
        var k = 0.035 + i * 0.012;
        a.__x += (tx - a.__x) * k;
        a.__y += (ty - a.__y) * k;
        a.style.transform = 'translate(' + a.__x.toFixed(1) + 'px,' + a.__y.toFixed(1) + 'px)';
      });
      requestAnimationFrame(loop);
    }
    requestAnimationFrame(loop);
  }

  if (!html.classList.contains('building') || html.classList.contains('done')) {
    // Intro already seen this session: skip the build, keep the cursors as followers.
    html.classList.add('done');
    agents.forEach(function (a) { a.style.transition = 'none'; });
    startAmbient();
    return;
  }

  var targets = Array.prototype.slice.call(document.querySelectorAll('[data-build]'))
    .sort(function (a, b) { return a.getAttribute('data-build') - b.getAttribute('data-build'); });
  var step = 260, timers = [], finished = false;
  skipBtn.hidden = false;

  function finish() {
    if (finished) return;
    finished = true;
    timers.forEach(clearTimeout);
    targets.forEach(function (t) { t.classList.add('built'); });
    html.classList.add('done');
    skipBtn.hidden = true;
    try { sessionStorage.setItem('built', '1'); } catch (e) {}
    startAmbient();
  }
  skipBtn.addEventListener('click', finish);

  targets.forEach(function (t, i) {
    timers.push(setTimeout(function () {
      var a = agents[i % agents.length], r = t.getBoundingClientRect();
      var x = Math.min(Math.max(r.left + Math.min(r.width * 0.72, r.width - 8), 12), window.innerWidth - 40);
      var y = Math.min(Math.max(r.top + r.height * 0.55, 12), window.innerHeight - 40);
      place(a, x, y);
      timers.push(setTimeout(function () {
        ping(a, x + 2, y + 2);
        t.classList.add('built');
      }, 430));
    }, 350 + i * step));
  });
  timers.push(setTimeout(finish, 350 + targets.length * step + 1100));
})();
